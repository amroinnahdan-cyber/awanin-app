#!/usr/bin/env node
/**
 * Regenerate `src/cities.ts` from the Expo app's city table.
 *
 * The app owns the list (`../src/data/indonesiaCities.ts`, derived from
 * GeoNames); the server only mirrors it so alerts can be titled with the city a
 * device picked. Running this keeps the mirror exact — same slugs, names,
 * coordinates and IANA zones — and prints how many cities were written.
 *
 * Usage (from `server/`): `npm run sync-cities`
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const serverRoot = join(here, '..');
const appCities = join(serverRoot, '..', 'src', 'data', 'indonesiaCities.ts');
const output = join(serverRoot, 'src', 'cities.ts');

function fail(message) {
  console.error(`sync-cities: ${message}`);
  process.exit(1);
}

let source;
try {
  source = readFileSync(appCities, 'utf8');
} catch {
  fail(`tidak bisa membaca ${appCities}`);
}

// The table is an array literal of object literals; parse the objects instead
// of matching whole lines, so a reformat (one field per line) still works.
const block = source.match(/export const INDONESIA_CITIES[^=]*=\s*\[([\s\S]*?)\n\];/);
if (!block) fail('array INDONESIA_CITIES tidak ditemukan di file app');

function field(body, key, pattern) {
  const match = body.match(pattern);
  if (!match) fail(`entri kota tanpa "${key}": ${body.trim().slice(0, 80)}`);
  return match[1];
}

const cities = [...block[1].matchAll(/\{([^{}]*)\}/g)].map(([, body]) => ({
  slug: field(body, 'slug', /slug:\s*'([^']+)'/),
  name: field(body, 'name', /name:\s*'([^']+)'/),
  area: field(body, 'province', /province:\s*'([^']+)'/),
  latitude: Number(field(body, 'latitude', /latitude:\s*(-?[\d.]+)/)),
  longitude: Number(field(body, 'longitude', /longitude:\s*(-?[\d.]+)/)),
  timezone: field(body, 'timezone', /timezone:\s*'([^']+)'/),
}));

if (cities.length === 0) fail('tidak ada kota yang terbaca dari file app');

const slugs = new Set();
for (const city of cities) {
  if (slugs.has(city.slug)) fail(`slug ganda: ${city.slug}`);
  slugs.add(city.slug);
  if (!Number.isFinite(city.latitude) || city.latitude < -90 || city.latitude > 90) {
    fail(`latitude tidak valid untuk ${city.slug}`);
  }
  if (!Number.isFinite(city.longitude) || city.longitude < -180 || city.longitude > 180) {
    fail(`longitude tidak valid untuk ${city.slug}`);
  }
}

const rows = cities.map(
  (city) =>
    `  { slug: '${city.slug}', name: '${city.name}', area: '${city.area}', ` +
    `latitude: ${city.latitude}, longitude: ${city.longitude}, timezone: '${city.timezone}' },`,
);

const content = `import type { Location } from './locations.js';

/**
 * The nationwide cities the app can monitor, mirrored from
 * \`src/data/indonesiaCities.ts\` in the Expo app.
 *
 * Without them the server only knew the five showcase points in Jakarta, so a
 * device that picked Bandung (slug and coordinates straight from the app) was
 * resolved by coordinates and every alert was titled "Lokasi saya". Keep this
 * table in sync with the app: same slug, name, coordinates and IANA zone.
 *
 * Generated by \`npm run sync-cities\` — edit the app's table, not this file.
 */
export const CITY_LOCATIONS: Location[] = [
${rows.join('\n')}
];
`;

let current = '';
try {
  current = readFileSync(output, 'utf8');
} catch {
  // First run: the file does not exist yet.
}

if (current === content) {
  console.log(`sync-cities: src/cities.ts sudah sinkron (${cities.length} kota)`);
} else {
  writeFileSync(output, content);
  console.log(`sync-cities: src/cities.ts diperbarui (${cities.length} kota)`);
}
